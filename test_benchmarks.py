def get_config(Z):
    if Z in EXCEPT:
        return [{'n': n, 'l': l, 'c': c} for n, l, c in EXCEPT[Z]]
    rem = Z
    cfg = []
    for n, l, m in AUFBAU:
        if rem <= 0:
            break
        c = min(rem, m)
        cfg.append({'n': n, 'l': l, 'c': c})
        rem -= c
    return cfg

def slater(cfg, orbital):
    n = int(orbital[0])
    lc = orbital[1]
    l = LS.index(lc)
    tgt = next((c for c in cfg if c['n'] == n and c['l'] == l), None)
    if not tgt:
        return None

    S = 0.0
    if lc in ('s', 'p'):
        same_shell = 0
        for c in cfg:
            if c['n'] == n and (c['l'] == 0 or c['l'] == 1):
                if c['l'] == l:
                    same_shell += c['c'] - 1
                else:
                    same_shell += c['c']
        sigma = 0.30 if n == 1 else 0.35
        S += round(same_shell * sigma, 2)

        if n > 1:
            nm1 = sum(c['c'] for c in cfg if c['n'] == n - 1)
            S += round(nm1 * 0.85, 2)

        if n > 2:
            inner = sum(c['c'] for c in cfg if c['n'] <= n - 2)
            S += round(inner * 1.00, 2)
    else:
        same = tgt['c'] - 1
        S += round(same * 0.35, 2)

        my_idx = next(i for i, (an, al) in enumerate(SLATER_DF) if an == n and al == l)
        left = 0
        for i in range(my_idx):
            an, al = SLATER_DF[i]
            f = next((c for c in cfg if c['n'] == an and c['l'] == al), None)
            if f:
                left += f['c']
        S += round(left * 1.00, 2)

    return round(S, 2)

